import React, { useEffect, useState } from 'react';
import { useLocation, useNavigate } from 'react-router-dom';
import { ArrowLeft, Download, Share2, Home as HomeIcon } from 'lucide-react';
import ResultDetails from '../components/ResultDetails';

const Result = () => {
  const location = useLocation();
  const navigate = useNavigate();
  const [result, setResult] = useState(null);

  useEffect(() => {
    // Get result from navigation state
    if (location.state?.result) {
      setResult(location.state.result);
    } else {
      // If no result, redirect to scan page
      navigate('/scan');
    }
  }, [location, navigate]);

  // Download result as text file
  const downloadResult = () => {
    if (!result) return;

    const textContent = `
NeuroScan AI - Stroke Risk Assessment Result
============================================

Scan Date: ${new Date(result.timestamp).toLocaleString()}

Risk Level: ${result.risk}
Confidence: ${(result.confidence * 100).toFixed(0)}%
Risk Score: ${(result.score * 100).toFixed(1)}%

Feature Analysis:
-----------------
${Object.entries(result.features)
  .map(([key, value]) => `${key}: ${(value * 100).toFixed(1)}%`)
  .join('\n')}

Explanation:
${result.explanation || 'N/A'}

Disclaimer:
This is a pre-diagnostic screening tool, not a medical diagnosis.
Always consult healthcare professionals for proper medical assessment.

Generated by NeuroScan AI
Microsoft Imagine Cup 2025
    `.trim();

    const blob = new Blob([textContent], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `neuroscan-result-${Date.now()}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  // Share result (Web Share API)
  const shareResult = async () => {
    if (!result) return;

    const shareData = {
      title: 'NeuroScan AI Result',
      text: `My stroke risk assessment: ${result.risk} Risk (${(
        result.confidence * 100
      ).toFixed(0)}% confidence)`,
    };

    try {
      if (navigator.share) {
        await navigator.share(shareData);
      } else {
        // Fallback: copy to clipboard
        await navigator.clipboard.writeText(shareData.text);
        alert('Result copied to clipboard!');
      }
    } catch (err) {
      console.error('Error sharing:', err);
    }
  };

  if (!result) {
    return (
      <div className="container mx-auto px-4 py-16 text-center">
        <p className="text-gray-600">Loading results...</p>
      </div>
    );
  }

  return (
    <div className="min-h-screen bg-gray-50 py-8">
      <div className="container mx-auto px-4 max-w-4xl">
        {/* Header */}
        <div className="flex items-center justify-between mb-8">
          <button
            onClick={() => navigate('/scan')}
            className="flex items-center space-x-2 text-gray-600 hover:text-gray-900 transition-colors"
          >
            <ArrowLeft className="w-5 h-5" />
            <span className="font-medium">New Scan</span>
          </button>

          <div className="flex items-center space-x-3">
            <button
              onClick={downloadResult}
              className="p-2 rounded-lg hover:bg-gray-200 transition-colors"
              title="Download Results"
            >
              <Download className="w-5 h-5 text-gray-600" />
            </button>

            <button
              onClick={shareResult}
              className="p-2 rounded-lg hover:bg-gray-200 transition-colors"
              title="Share Results"
            >
              <Share2 className="w-5 h-5 text-gray-600" />
            </button>
          </div>
        </div>

        {/* Result Details */}
        <ResultDetails result={result} />

        {/* Action Buttons */}
        <div className="mt-8 flex flex-col sm:flex-row gap-4 justify-center">
          <button
            onClick={() => navigate('/scan')}
            className="btn-primary flex items-center justify-center space-x-2"
          >
            <Camera className="w-5 h-5" />
            <span>Scan Again</span>
          </button>

          <button
            onClick={() => navigate('/dashboard')}
            className="btn-secondary flex items-center justify-center space-x-2"
          >
            <BarChart3 className="w-5 h-5" />
            <span>View History</span>
          </button>

          <button
            onClick={() => navigate('/')}
            className="btn-secondary flex items-center justify-center space-x-2"
          >
            <HomeIcon className="w-5 h-5" />
            <span>Home</span>
          </button>
        </div>

        {/* Emergency Contact Section */}
        {result.risk?.toLowerCase() === 'high' && (
          <div className="mt-8 card bg-red-50 border-2 border-red-300">
            <div className="text-center">
              <h3 className="text-xl font-bold text-red-900 mb-3">
                ⚠️ High Risk Detected
              </h3>
              <p className="text-red-800 mb-4">
                If you are experiencing stroke symptoms, seek immediate medical
                attention.
              </p>
              <div className="grid sm:grid-cols-2 gap-4">
                <a
                  href="tel:911"
                  className="bg-red-600 hover:bg-red-700 text-white font-bold py-3 px-6 rounded-lg transition-colors"
                >
                  📞 Call Emergency (911)
                </a>
                <a
                  href="https://www.stroke.org/en/about-stroke/stroke-symptoms"
                  target="_blank"
                  rel="noopener noreferrer"
                  className="bg-red-100 hover:bg-red-200 text-red-900 font-bold py-3 px-6 rounded-lg transition-colors border-2 border-red-300"
                >
                  Learn Stroke Symptoms
                </a>
              </div>
            </div>
          </div>
        )}

        {/* FAST Test Reference */}
        <div className="mt-8 card">
          <h3 className="text-xl font-bold text-gray-900 mb-4">
            Know the FAST Test for Stroke
          </h3>
          <div className="grid md:grid-cols-2 gap-4">
            <div className="p-4 bg-blue-50 rounded-lg">
              <p className="font-bold text-blue-900 mb-2">F - Face Drooping</p>
              <p className="text-sm text-blue-800">
                Does one side of the face droop or is it numb? Ask the person to
                smile.
              </p>
            </div>
            <div className="p-4 bg-blue-50 rounded-lg">
              <p className="font-bold text-blue-900 mb-2">A - Arm Weakness</p>
              <p className="text-sm text-blue-800">
                Is one arm weak or numb? Ask the person to raise both arms.
              </p>
            </div>
            <div className="p-4 bg-blue-50 rounded-lg">
              <p className="font-bold text-blue-900 mb-2">S - Speech Difficulty</p>
              <p className="text-sm text-blue-800">
                Is speech slurred? Is the person unable to speak or hard to
                understand?
              </p>
            </div>
            <div className="p-4 bg-blue-50 rounded-lg">
              <p className="font-bold text-blue-900 mb-2">T - Time to Call 911</p>
              <p className="text-sm text-blue-800">
                If you see any of these signs, call 911 immediately.
              </p>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};

// Import missing icons
import { Camera, BarChart3 } from 'lucide-react';

export default Result;
